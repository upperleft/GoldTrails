CREATE TABLE IF NOT EXISTS connection_adjacency (
 state_code CHAR(2) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 neighbor_code CHAR(2) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 PRIMARY KEY(state_code,neighbor_code),
 FOREIGN KEY(state_code) REFERENCES connection_states(code),
 FOREIGN KEY(neighbor_code) REFERENCES connection_states(code), CHECK(state_code<>neighbor_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS connection_events (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 organizer_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 state_code CHAR(2) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 title VARCHAR(160) NOT NULL,
 status ENUM('draft','published','cancelled') NOT NULL DEFAULT 'draft',
 visibility ENUM('public','plus') NOT NULL DEFAULT 'public',
 moderated BOOLEAN NOT NULL DEFAULT FALSE,
 mode ENUM('in-person','online','hybrid') NOT NULL,
 category VARCHAR(40) NOT NULL, experience_level VARCHAR(30) NOT NULL,
 start_utc DATETIME(6) NOT NULL, end_utc DATETIME(6) NOT NULL,
 deadline_utc DATETIME(6) NULL, capacity INT UNSIGNED NULL,
 waitlist_enabled BOOLEAN NOT NULL DEFAULT FALSE,
 details_json JSON NOT NULL,
 meeting_cipher TEXT NULL,
 revision INT UNSIGNED NOT NULL DEFAULT 1,
 series_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
 FOREIGN KEY(organizer_id) REFERENCES member_accounts(id), FOREIGN KEY(state_code) REFERENCES connection_states(code),
 INDEX connections_discover(status,visibility,start_utc,state_code), INDEX connections_state(state_code,status,start_utc),
 INDEX connections_organizer(organizer_id,start_utc), INDEX connections_series(series_id,start_utc),
 CHECK(end_utc>start_utc), CHECK(capacity IS NULL OR capacity BETWEEN 1 AND 10000), CHECK(revision>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS connection_rsvps (
 event_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL, account_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 status ENUM('yes','waitlisted','cancelled') NOT NULL,
 attended BOOLEAN NOT NULL DEFAULT FALSE,
 joined_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
 PRIMARY KEY(event_id,account_id), FOREIGN KEY(event_id) REFERENCES connection_events(id),
 FOREIGN KEY(account_id) REFERENCES member_accounts(id),
 INDEX connections_rsvp_account(account_id,status,event_id), INDEX connections_waitlist(event_id,status,joined_at,account_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS connection_follows (
 account_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL, state_code CHAR(2) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), PRIMARY KEY(account_id,state_code),
 FOREIGN KEY(account_id) REFERENCES member_accounts(id), FOREIGN KEY(state_code) REFERENCES connection_states(code),
 INDEX connections_follow_state(state_code,account_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS connection_preferences (
 account_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 new_events BOOLEAN NOT NULL DEFAULT FALSE, updates BOOLEAN NOT NULL DEFAULT FALSE,
 reminders BOOLEAN NOT NULL DEFAULT FALSE, rsvp BOOLEAN NOT NULL DEFAULT FALSE,
 FOREIGN KEY(account_id) REFERENCES member_accounts(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS connection_comments (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY, event_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL, author_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 kind ENUM('comment','announcement','recap') NOT NULL DEFAULT 'comment', body TEXT NOT NULL,
 hidden BOOLEAN NOT NULL DEFAULT FALSE, deleted BOOLEAN NOT NULL DEFAULT FALSE,
 revision INT UNSIGNED NOT NULL DEFAULT 1,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
 FOREIGN KEY(event_id) REFERENCES connection_events(id), FOREIGN KEY(author_id) REFERENCES member_accounts(id),
 INDEX connections_discussion(event_id,created_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS connection_photos (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY, event_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL, author_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 kind ENUM('cover','experience') NOT NULL, caption VARCHAR(240) NOT NULL,
 content MEDIUMBLOB NOT NULL, mime_type VARCHAR(30) NOT NULL DEFAULT 'image/jpeg',
 hidden BOOLEAN NOT NULL DEFAULT FALSE,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY(event_id) REFERENCES connection_events(id), FOREIGN KEY(author_id) REFERENCES member_accounts(id),
 INDEX connections_photo_event(event_id,kind,hidden,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS connection_reports (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY, event_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL, reporter_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 target_type ENUM('event','comment','photo') NOT NULL, target_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 reason VARCHAR(1000) NOT NULL, status ENUM('open','resolved') NOT NULL DEFAULT 'open',
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 FOREIGN KEY(event_id) REFERENCES connection_events(id), FOREIGN KEY(reporter_id) REFERENCES member_accounts(id),
 INDEX connections_reports(status,event_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS connection_notifications (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY, event_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL, account_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 kind ENUM('new_event','rsvp','reminder','update','cancellation','promotion','announcement') NOT NULL,
 event_revision INT UNSIGNED NOT NULL,
 due_at DATETIME(6) NOT NULL, status ENUM('pending','sending','sent','skipped','failed','uncertain') NOT NULL DEFAULT 'pending',
 attempts SMALLINT UNSIGNED NOT NULL DEFAULT 0,
 lease_until DATETIME(6) NULL, first_attempt_at DATETIME(6) NULL, payload_json JSON NULL, provider_id VARCHAR(180) NULL,
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), sent_at DATETIME(6) NULL,
 UNIQUE connections_notification_once(event_id,account_id,kind,event_revision),
 FOREIGN KEY(event_id) REFERENCES connection_events(id), FOREIGN KEY(account_id) REFERENCES member_accounts(id),
 INDEX connections_outbox(status,due_at,lease_until)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS connection_audit (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY, account_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL, event_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
 action VARCHAR(50) NOT NULL, created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 INDEX connections_audit_event(event_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS connection_limits (
 account_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY, attempts INT UNSIGNED NOT NULL DEFAULT 0,
 window_started DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), FOREIGN KEY(account_id) REFERENCES member_accounts(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS connection_calendar_copies (
 account_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 event_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 calendar_event_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 PRIMARY KEY(account_id,event_id), FOREIGN KEY(account_id) REFERENCES member_accounts(id),
 FOREIGN KEY(event_id) REFERENCES connection_events(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS connection_dispatch_control (
 id TINYINT UNSIGNED PRIMARY KEY, next_send_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), CHECK(id=1)
) ENGINE=InnoDB;
